const I18N_LANGS = { it: "Italiano", de: "Deutsch", fr: "Français", en: "English" };
const I18N_LOCALE = { it: "it-CH", de: "de-CH", fr: "fr-CH", en: "en-GB" };

function detectLang() {
  try {
    const stored = localStorage.getItem("storie_lang");
    if (stored && I18N_LANGS[stored]) return stored;
  } catch (_) { /* storage blocked */ }
  const m = document.cookie.match(/(?:^|; )storie_lang=(\w+)/);
  if (m && I18N_LANGS[m[1]]) return m[1];
  const nav = (navigator.language || "en").slice(0, 2).toLowerCase();
  return I18N_LANGS[nav] ? nav : "en";
}
const LANG = detectLang();
const DICT = I18N[LANG] || {};
document.documentElement.lang = LANG;

/** t("Letta {uid}", {uid}) — Italian source string in, current language out. */
function t(key, vars) {
  let s = DICT[key] !== undefined ? DICT[key] : key;
  if (vars) for (const k in vars) s = s.split(`{${k}}`).join(vars[k]);
  return s;
}
function setLang(lang) {
  try { localStorage.setItem("storie_lang", lang); } catch (_) { /* ignore */ }
  document.cookie = `storie_lang=${lang}; path=/; max-age=31536000; SameSite=Lax`;
  location.reload();
}

/** Translate static markup: text nodes and a few attributes whose exact text is a known key. */
function translateTree(root) {
  if (LANG === "it" || !root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const n of nodes) {
    const raw = n.nodeValue;
    const trimmed = raw.trim();
    if (trimmed && DICT[trimmed] !== undefined) n.nodeValue = raw.replace(trimmed, DICT[trimmed]);
  }
  const els = root.querySelectorAll ? root.querySelectorAll("[placeholder],[title],[aria-label]") : [];
  for (const el of els) {
    for (const a of ["placeholder", "title", "aria-label"]) {
      const v = el.getAttribute(a);
      if (v && DICT[v] !== undefined) el.setAttribute(a, DICT[v]);
    }
  }
}
if (LANG !== "it") {
  const start = () => {
    translateTree(document.body);
    new MutationObserver((muts) => {
      for (const m of muts) for (const n of m.addedNodes) {
        if (n.nodeType === 1) translateTree(n);
        else if (n.nodeType === 3) translateTree(n.parentNode);
      }
    }).observe(document.body, { childList: true, subtree: true });
  };
  if (document.body) start(); else document.addEventListener("DOMContentLoaded", start);
}
